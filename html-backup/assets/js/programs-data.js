// Accessor functions
window.getProgramById = function(id) {
    if (!id || !window.IZZY_PROGRAMS) return null;
    return window.IZZY_PROGRAMS.find(p => p.id === id || p.id === id.toLowerCase()) || null;
};

window.getCitizenshipPrograms = function() {
    return window.IZZY_PROGRAMS.filter(p => p.type === 'citizenship');
};

window.getResidencyPrograms = function(region) {
    if (!region) return window.IZZY_PROGRAMS.filter(p => p.type === 'residency');
    return window.IZZY_PROGRAMS.filter(p => p.type === 'residency' && p.region.toLowerCase() === region.toLowerCase());
};

window.getFeaturedPrograms = function(limit = 6) {
    return window.IZZY_PROGRAMS.slice(0, limit);
};
